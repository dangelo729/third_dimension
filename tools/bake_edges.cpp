// bake_edges — host-side bake of one mesh's TD_OUTLINE edge table into a
// header (TD edges format 1), so the table sits in flash beside the mesh and
// the board never builds it: no 3 B/loop-slot table in RAM, and none of the
// build's scratch (16 B/vertex + 8 B/loop slot + 12 B/face). it runs the
// library's own TD_EdgeTable::build, so the baked table is exactly the one
// the renderer would build on the host. one binary per mesh: the mesh
// header comes in with -include, its TD_Mesh symbol with -DTD_BAKE_MESH.
// build and run from this directory with:
//
//   clang++ -std=c++17 -O1 -ffp-contract=off -I../src -include Model.h -DTD_BAKE_MESH=model_mesh bake_edges.cpp ../src/TD_Mesh.cpp ../src/internal/td_edge_table.cpp -o bake_edges && ./bake_edges model 0.8 > ModelEdges.h
//
// arguments: the symbol prefix (the header emits <prefix>_edges) and the
// crease angle in radians — the value the sketch passes to
// setOutlineCrease, parsed as a float, so 0.8 here matches 0.8f there. the
// sketch hands the table in at setup:
//
//   scene.setOutlineEdges(model_mesh, model_edges);
//
// re-bake whenever the mesh or the crease changes: a table whose counts or
// crease don't match is ignored, and the table builds at runtime again.

#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "TD_Mesh.h"
#include "internal/td_edge_table.h"

#ifndef TD_BAKE_MESH
#error "define TD_BAKE_MESH as the mesh symbol, and -include its header"
#endif

#define TD_BAKE_STR2(x) #x
#define TD_BAKE_STR(x) TD_BAKE_STR2(x)

// a float as a C++ literal that round-trips exactly: %.9g, with ".0" added
// where it would otherwise read as an integer ("1f" is not a literal).
static void printFloatLiteral(float v) {
  char buf[32];
  snprintf(buf, sizeof buf, "%.9g", (double)v);
  printf("%s%sf", buf, strpbrk(buf, ".e") ? "" : ".0");
}

int main(int argc, char **argv) {
  if (argc != 3) {
    fprintf(stderr, "usage: bake_edges <prefix> <crease radians>\n");
    return 2;
  }
  const char *prefix = argv[1];
  char *end = nullptr;
  const float crease = strtof(argv[2], &end);
  if (end == argv[2] || *end != '\0' || !isfinite(crease)) {
    fprintf(stderr, "bake_edges: '%s' is not a crease angle in radians\n", argv[2]);
    return 2;
  }

  const TD_Mesh &mesh = TD_BAKE_MESH;
  if (!td_validateMesh(mesh) || mesh.faceVertCount == 0) {
    fprintf(stderr, "bake_edges: %s is not a valid, non-empty mesh\n", TD_BAKE_STR(TD_BAKE_MESH));
    return 1;
  }
  TD_EdgeTable table;
  if (!table.build(mesh, crease)) {
    fprintf(stderr, "bake_edges: the edge table build failed (out of memory)\n");
    return 1;
  }

  const unsigned n = mesh.faceVertCount;
  printf("// SPDX-License-Identifier: MIT\n");
  printf("// generated by tools/bake_edges.cpp from %s — do not edit.\n", TD_BAKE_STR(TD_BAKE_MESH));
  printf("// TD_OUTLINE edge table: %u loop slots (%u verts, %u faces), crease %.9g rad.\n", n,
         (unsigned)mesh.nverts, (unsigned)mesh.nfaces, (double)crease);
  printf("// re-bake whenever the mesh or the crease changes.\n");
  printf("#pragma once\n");
  printf("#include <TD_MeshEdges.h>\n\n");
  printf("#if !defined(TD_EDGES_FORMAT) || TD_EDGES_FORMAT != 1\n");
  printf("#error \"This edges header is TD edges format 1 — re-bake with a matching tools/bake_edges.cpp\"\n");
  printf("#endif\n\n");

  printf("static const uint16_t %s_edge_opp[%u] TD_PROGMEM = {\n", prefix, n);
  for (unsigned i = 0; i < n; ++i)
    printf("%s%u,%s", i % 16 == 0 ? "  " : " ", (unsigned)table.opp[i], i % 16 == 15 || i + 1 == n ? "\n" : "");
  printf("};\n\n");

  printf("static const uint8_t %s_edge_flags[%u] TD_PROGMEM = {\n", prefix, n);
  for (unsigned i = 0; i < n; ++i)
    printf("%s%u,%s", i % 32 == 0 ? "  " : " ", (unsigned)table.flags[i], i % 32 == 31 || i + 1 == n ? "\n" : "");
  printf("};\n\n");

  printf("// TD edges format 1 — all six fields explicit, in declaration order.\n");
  printf("static constexpr TD_MeshEdges %s_edges = {\n", prefix);
  printf("  %s_edge_opp,\n", prefix);
  printf("  %s_edge_flags,\n", prefix);
  printf("  %u,  // nverts\n", (unsigned)mesh.nverts);
  printf("  %u,  // nfaces\n", (unsigned)mesh.nfaces);
  printf("  %u,  // faceVertCount\n", n);
  printf("  ");
  printFloatLiteral(crease);
  printf(",  // crease, radians\n");
  printf("};\n");

  table.release();
  return 0;
}
